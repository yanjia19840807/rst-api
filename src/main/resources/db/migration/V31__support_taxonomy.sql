-- Global Production Support Category / Activity catalog, maintained by LTH.

CREATE TABLE support_category (
    id UUID PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    status VARCHAR(20) NOT NULL
        CHECK (status IN ('ACTIVE', 'INACTIVE')),
    display_order INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(64),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by VARCHAR(64),
    deleted_at TIMESTAMPTZ,
    deleted_by VARCHAR(64),
    row_version BIGINT NOT NULL DEFAULT 0
);

CREATE UNIQUE INDEX uk_support_category_name_active
    ON support_category (lower(name))
    WHERE deleted_at IS NULL;

CREATE TABLE support_activity (
    id UUID PRIMARY KEY,
    category_id UUID NOT NULL REFERENCES support_category(id),
    name VARCHAR(240) NOT NULL,
    status VARCHAR(20) NOT NULL
        CHECK (status IN ('ACTIVE', 'INACTIVE')),
    display_order INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(64),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by VARCHAR(64),
    deleted_at TIMESTAMPTZ,
    deleted_by VARCHAR(64),
    row_version BIGINT NOT NULL DEFAULT 0
);

CREATE UNIQUE INDEX uk_support_activity_name_active
    ON support_activity (category_id, lower(name))
    WHERE deleted_at IS NULL;

CREATE INDEX ix_support_activity_category
    ON support_activity (category_id)
    WHERE deleted_at IS NULL;

ALTER TABLE exercise_production_support_item
    ADD COLUMN category_id UUID REFERENCES support_category(id),
    ADD COLUMN activity_id UUID REFERENCES support_activity(id);

CREATE INDEX ix_exercise_production_support_item_category
    ON exercise_production_support_item (category_id);

CREATE INDEX ix_exercise_production_support_item_activity
    ON exercise_production_support_item (activity_id);

