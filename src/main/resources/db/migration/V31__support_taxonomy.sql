UPDATE exercise_production_support_item i
SET category_id = c.id
FROM support_category c
WHERE i.category_id IS NULL
  AND c.deleted_at IS NULL
  AND lower(i.category) = lower(c.name);

UPDATE exercise_production_support_item i
SET activity_id = a.id
FROM support_activity a
WHERE i.activity_id IS NULL
  AND i.category_id = a.category_id
  AND a.deleted_at IS NULL
  AND lower(i.activity) = lower(a.name);
